/**
 * Download the three web fonts into assets/fonts/ and write assets/fonts.css.
 *
 * Why self-host: Chromium will not embed a web font into its PDF when the page
 * is opened from file:// and the font came from another origin — it rasterises
 * the text into Type3 fonts instead, which look soft and defeat text selection.
 * Local font files, loaded from the same origin as the page, embed properly.
 *
 * Fonts are SIL Open Font Licensed, so shipping the files in the repository is
 * allowed. Run once; re-run only to change weights.
 *
 * Run: node docs/rewards/hr-interview-playbook/fetch-fonts.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, "assets", "fonts");

// A desktop Chrome UA, so Google Fonts serves woff2 rather than a legacy format.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

/*
 * One request per weight, never a combined one. Asking for several weights at
 * once returns a single variable font covering the whole axis, and Chromium
 * rasterises variable-axis text into Type3 fonts when it prints — soft edges,
 * no text selection. A single-weight request returns a narrow instance that
 * embeds as a normal TrueType subset.
 */
const families = [
  { name: "Manrope", css: "Manrope", weights: [500, 600, 700, 800] },
  { name: "Plus Jakarta Sans", css: "Plus+Jakarta+Sans", weights: [400, 500, 600, 700, 800] },
  { name: "JetBrains Mono", css: "JetBrains+Mono", weights: [400, 500, 700] },
];

await fs.mkdir(outDir, { recursive: true });

const blocks = [];
for (const family of families) {
  for (const wanted of family.weights) {
  const url = `https://fonts.googleapis.com/css2?family=${family.css}:wght@${wanted}&display=swap`;
  const css = await fetch(url, { headers: { "User-Agent": UA } }).then((response) => response.text());

  // Keep only the latin and latin-ext faces: Indonesian and English need
  // nothing else, and the rest would double the file size.
  const faces = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/g)].filter(([, subset]) =>
    ["latin", "latin-ext"].includes(subset),
  );

  for (const [, subset, block] of faces) {
    const weight = String(wanted);
    const style = /font-style:\s*(\w+)/.exec(block)?.[1] ?? "normal";
    const src = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
    if (!src) continue;

    const slug = `${family.name.toLowerCase().replace(/\s+/g, "-")}-${weight}-${subset}.woff2`;
    const bytes = Buffer.from(await fetch(src, { headers: { "User-Agent": UA } }).then((r) => r.arrayBuffer()));
    await fs.writeFile(path.join(outDir, slug), bytes);

    blocks.push(
      `@font-face {\n  font-family: "${family.name}";\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: block;\n  src: url("fonts/${slug}") format("woff2");${
        range ? `\n  unicode-range: ${range};` : ""
      }\n}`,
    );
    console.log(`${slug} — ${(bytes.length / 1024).toFixed(0)} KB`);
  }
  }
}

await fs.writeFile(
  path.join(here, "assets", "fonts.css"),
  `/* Generated by fetch-fonts.mjs. Google Fonts, SIL Open Font License. */\n\n${blocks.join("\n\n")}\n`,
  "utf8",
);
console.log(`\nwrote assets/fonts.css — ${blocks.length} faces`);
